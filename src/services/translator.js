class TranslationEngine {
  constructor() {
    this.currentLang = localStorage.getItem('agri_lang') || 'en';
    this.observer = null;
    this.init();
  }

  init() {
    if (typeof window === 'undefined') return;

    // Apply saved language on start
    if (this.currentLang !== 'en') {
      setTimeout(() => this.translateDOM(this.currentLang), 300);
    }

    // Set up MutationObserver to translate dynamic elements as user navigates
    if (typeof MutationObserver !== 'undefined') {
      this.observer = new MutationObserver((mutations) => {
        if (this.currentLang === 'en') return;
        let shouldTranslate = false;
        for (const m of mutations) {
          if (m.addedNodes && m.addedNodes.length > 0) {
            shouldTranslate = true;
            break;
          }
        }
        if (shouldTranslate) {
          this.translateDOM(this.currentLang);
        }
      });

      window.addEventListener('DOMContentLoaded', () => {
        this.observer.observe(document.body, {
          childList: true,
          subtree: true
        });
      });
    }
  }

  setLanguage(targetLang) {
    this.currentLang = targetLang;
    localStorage.setItem('agri_lang', targetLang);

    if (targetLang === 'en') {
      this.restoreEnglish();
      this.triggerGoogleTranslate('en');
    } else {
      this.translateDOM(targetLang);
      this.triggerGoogleTranslate(targetLang);
    }
  }

  triggerGoogleTranslate(langCode) {
    if (typeof window === 'undefined') return;
    try {
      const target = langCode === 'en' ? 'en' : langCode;
      document.cookie = `googtrans=/en/${target}; path=/;`;
      document.cookie = `googtrans=/en/${target}; domain=${window.location.hostname}; path=/;`;

      const select = document.querySelector('.goog-te-combo');
      if (select) {
        select.value = target;
        select.dispatchEvent(new Event('change'));
      }
    } catch (e) {
      console.warn('Google translate bridge note:', e);
    }
  }

  translateDOM(lang) {
    if (typeof document === 'undefined' || lang === 'en') return;

    // Helper to walk text nodes
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode: (node) => {
          const parent = node.parentElement;
          if (!parent) return NodeFilter.FILTER_REJECT;
          const tag = parent.tagName.toLowerCase();
          if (['script', 'style', 'textarea', 'code', 'pre'].includes(tag)) {
            return NodeFilter.FILTER_REJECT;
          }
          if (parent.classList.contains('no-translate')) {
            return NodeFilter.FILTER_REJECT;
          }
          return NodeFilter.FILTER_ACCEPT;
        }
      }
    );

    const nodesToTranslate = [];
    let currentNode;
    while ((currentNode = walker.nextNode())) {
      const text = currentNode.nodeValue.trim();
      if (text.length > 0) {
        nodesToTranslate.push(currentNode);
      }
    }

    // Process nodes
    nodesToTranslate.forEach((node) => {
      const rawText = node.nodeValue;
      const trimmed = rawText.trim();

      // Check exact dictionary match
      if (DICTIONARY[trimmed] && DICTIONARY[trimmed][lang]) {
        const parent = node.parentElement;
        if (parent && !parent.getAttribute('data-orig-text')) {
          parent.setAttribute('data-orig-text', trimmed);
        }
        node.nodeValue = rawText.replace(trimmed, DICTIONARY[trimmed][lang]);
        return;
      }

      // Check partial phrase replacements
      let modifiedText = rawText;
      let matched = false;
      for (const [key, trans] of Object.entries(DICTIONARY)) {
        if (key.length > 3 && modifiedText.includes(key) && trans[lang]) {
          const parent = node.parentElement;
          if (parent && !parent.getAttribute('data-orig-text')) {
            parent.setAttribute('data-orig-text', rawText);
          }
          modifiedText = modifiedText.replaceAll(key, trans[lang]);
          matched = true;
        }
      }

      if (matched) {
        node.nodeValue = modifiedText;
      }
    });

    // Also translate button and input placeholders
    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach((el) => {
      const ph = el.getAttribute('placeholder');
      if (ph && DICTIONARY[ph] && DICTIONARY[ph][lang]) {
        if (!el.getAttribute('data-orig-ph')) {
          el.setAttribute('data-orig-ph', ph);
        }
        el.setAttribute('placeholder', DICTIONARY[ph][lang]);
      }
    });
  }

  restoreEnglish() {
    if (typeof document === 'undefined') return;

    // Restore text nodes
    document.querySelectorAll('[data-orig-text]').forEach((el) => {
      const orig = el.getAttribute('data-orig-text');
      if (orig) {
        el.textContent = orig;
        el.removeAttribute('data-orig-text');
      }
    });

    // Restore placeholders
    document.querySelectorAll('[data-orig-ph]').forEach((el) => {
      const orig = el.getAttribute('data-orig-ph');
      if (orig) {
        el.setAttribute('placeholder', orig);
        el.removeAttribute('data-orig-ph');
      }
    });
  }
}

export const translator = new TranslationEngine();
export default translator;
